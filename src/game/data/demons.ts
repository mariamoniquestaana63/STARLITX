export function getDemon(floor: number): Demon {
  const idx = Math.min(floor - 1, DEMONS.length - 1);
  return DEMONS[idx];
}

export function getDemonStats(demon: Demon, floor: number) {
  const scaleFactor = 1 + Math.floor(floor / 10) * 0.15;
  return {
    health: Math.floor(demon.stats.health * scaleFactor),
    maxHealth: Math.floor(demon.stats.health * scaleFactor),
    attack: Math.floor(demon.stats.attack * scaleFactor),
    defense: Math.floor(demon.stats.defense * scaleFactor),
    speed: demon.stats.speed,
    xpReward: Math.floor(demon.stats.xpReward * scaleFactor),
    goldReward: Math.floor(demon.stats.goldReward * scaleFactor),
  };
}
